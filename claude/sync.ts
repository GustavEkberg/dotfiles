import { mkdir, readdir, unlink } from "node:fs/promises"
import { join, resolve } from "node:path"
import { agent, expand, mcp, object, permissions, strings, text, tools } from "./adapter"

const root = resolve(import.meta.dir, "..")
const source = object(Bun.JSON5.parse(await Bun.file(join(root, "opencode/opencode.json")).text()))
const overrides = object(await Bun.file(join(import.meta.dir, "settings.json")).json())
const check = process.argv.includes("--check")
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Usage: bun claude/sync.ts [--check]")
if (overrides.permissions !== undefined) throw new Error("Permissions belong in opencode/opencode.json")
const overrideHooks = object(overrides.hooks ?? {})
if (overrideHooks.PreToolUse !== undefined) throw new Error("PreToolUse adapters belong in claude/sync.ts")
const qmdNoRerank = strings(source.plugin).some((plugin) => plugin.endsWith("/qmd-no-rerank.ts"))

const nativeMcp = mcp(object(source.mcp))
const nativePermissions = permissions(object(source.permission), Object.keys(object(source.mcp)))
const directories = strings(nativePermissions.additionalDirectories)
const instructions = [
  "<!-- Generated by bun claude/sync.ts; edit OpenCode sources instead. -->",
  `@${join(root, "opencode/AGENTS.md")}`,
  ...strings(source.instructions).map((path) => `@${expand(path)}`),
  "",
]
for (const [name, raw] of Object.entries(object(source.references))) {
  const reference = object(raw)
  const path = reference.path !== undefined ? resolve(join(root, "opencode"), expand(text(reference.path)))
    : expand(`~/.local/share/opencode/repos/github.com/${text(reference.repository)}`)
  directories.push(path)
  instructions.push(`- Reference \`${name}\`: \`${path}\`. ${text(reference.description)}`)
}
nativePermissions.additionalDirectories = [...new Set(directories)]

const settings = {
  ...overrides,
  permissions: nativePermissions,
  pluginConfigs: {
    ...object(overrides.pluginConfigs ?? {}),
    "cc-plugin-agents-md@builtin": { options: { instructionFiles: "claude-md-and-agents-md" } },
  },
  extraKnownMarketplaces: {
    ...object(overrides.extraKnownMarketplaces ?? {}),
    dotfiles: { source: { source: "directory", path: import.meta.dir }, autoUpdate: false },
  },
  enabledPlugins: { ...object(overrides.enabledPlugins ?? {}), "opencode@dotfiles": true },
  hooks: {
    ...overrideHooks,
    PreToolUse: qmdNoRerank ? [
      {
        matcher: "mcp__qmd__query|mcp__plugin_opencode_qmd__query",
        hooks: [{ type: "command", command: `sh '${join(import.meta.dir, "hooks/qmd-no-rerank.sh")}'` }],
      },
    ] : [],
  },
}

const outputs = new Map<string, string>([
  ["generated/settings.json", `${JSON.stringify(settings, null, 2)}\n`],
  ["generated/CLAUDE.md", `${instructions.join("\n")}\n`],
  ["mcp/.mcp.json", `${JSON.stringify(nativeMcp, null, 2)}\n`],
])
for (const file of await readdir(join(root, "opencode/agent"))) {
  if (!file.endsWith(".md")) continue
  const name = file.slice(0, -3)
  const definition = agent(await Bun.file(join(root, "opencode/agent", file)).text())
  if (definition.metadata.disable === true) continue
  if (definition.metadata.mode !== "subagent") throw new Error(`Unsupported Claude agent mode: ${name}`)
  if (definition.metadata.model !== undefined) throw new Error(`Claude needs a native model mapping for ${name}`)
  const allowed = text(definition.metadata["allowed-tools"]).split(/,\s*/)
    .map((entry) => entry.split("(")[0]).filter((entry) => entry !== undefined)
  for (const key of Object.keys(object(definition.metadata.permission))) {
    if (tools[key] === undefined) throw new Error(`Unsupported agent permission: ${name}.${key}`)
  }
  const metadata = {
    name,
    description: text(definition.metadata.description),
    tools: [...new Set(allowed)],
    hooks: {
      PreToolUse: [{
        matcher: ".*",
        hooks: [{ type: "command", command: `bun '${join(import.meta.dir, "agent-permission.ts")}' '${name}'` }],
      }],
    },
  }
  outputs.set(`generated/agents/${file}`, `---\n${JSON.stringify(metadata, null, 2)}\n---\n<!-- Generated by bun claude/sync.ts; edit OpenCode sources instead. -->\n${definition.body}`)
}

let stale = false
for (const [path, content] of outputs) {
  const output = Bun.file(join(import.meta.dir, path))
  if (await output.exists() && await output.text() === content) continue
  if (check) {
    console.error(`Stale or missing: claude/${path}`)
    stale = true
  } else {
    await Bun.write(output, content)
    console.log(`Generated claude/${path}`)
  }
}
const agentDirectory = join(import.meta.dir, "generated/agents")
if (!check) await mkdir(agentDirectory, { recursive: true })
const generatedAgents = await readdir(agentDirectory).catch((error: unknown) => {
  if (object(error).code === "ENOENT") return []
  throw error
})
for (const file of generatedAgents) {
  const path = `generated/agents/${file}`
  if (outputs.has(path)) continue
  if (!file.endsWith(".md") || !(await Bun.file(join(agentDirectory, file)).text()).includes("<!-- Generated by bun claude/sync.ts; edit OpenCode sources instead. -->")) {
    throw new Error(`Unexpected file in generated agents: ${file}`)
  }
  if (check) {
    console.error(`Stale agent: claude/${path}`)
    stale = true
  } else {
    await unlink(join(agentDirectory, file))
    console.log(`Removed stale claude/${path}`)
  }
}
if (stale) process.exit(1)
